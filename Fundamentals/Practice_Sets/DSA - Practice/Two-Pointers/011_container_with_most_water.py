# Problem Description
# You are given an integer array height of length n. Find two lines that together with the x-axis form a container, 
# such that the container holds the most water.

# Return the maximum amount of water a container can store.

# Examples
# Example 1:
# Input: height = [1, 8, 6, 2, 5, 4, 8, 3, 7]
# Output: 49
# Example 2:
# Input: height = [1, 1]
# Output: 1
# Water Calculation Formula: Area = (right−left) × min(height[left],height[right])